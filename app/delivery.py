# Вес по виду оборудования, если в карточке не указан (допущение: брутто с упаковкой)
DEFAULT_WEIGHT = {"tire_changer_truck": 450, "balancer_truck": 200, "alignment_stand": 150, "compressor": 300,
                  "impact_wrench": 15, "jack": 60, "receiver": 150, "lift": 400}
FREE_KINDS = {"alignment_stand": "доставка стендов Техновектор бесплатная (условие с сайта компании)"}

# Тариф-допущение «сборный груз транспортной компанией»
PICKUP = 2500             # забор со склада, ₽
RATE = 0.012              # ₽ за кг·км
MIN_COST = 3500
LOCAL_COST = 3000         # Москва и область: машина до двери
LOCAL_PER_KG = 5


def find_city(text: str) -> str | None:
    t = (text or "").lower().replace("ё", "е")
    hits = [(m.start(), name) for pat, name, _ in CITIES for m in re.finditer(pat, t)]
    return max(hits)[1] if hits else None  # последнее упоминание в тексте


def _weight(p) -> float:
    for k, v in p.specs.items():
        if k.lower().startswith("вес"):
            m = re.search(r"\d+(?:[.,]\d+)?", str(v))
            if m:
                return float(m[0].replace(",", ".")) * 1.1  # +10% на упаковку
    return DEFAULT_WEIGHT.get(p.kind, 100)


def calc(items: list[dict], city: str | None = None, km: float | None = None) -> dict:
    """items: [{id, qty}]. Город из справочника или километры вручную."""
    products = load()
    if km is None and city:
        km = CITY_KM.get(city)
    if km is None:
        err = ("Город не найден в справочнике — укажите расстояние от Москвы, км" if city
               else "Город доставки не назван — укажите город или расстояние от Москвы, км")
        return {"ok": False, "error": err, "city": city}
    km = max(0.0, float(km))
    paid_w, free, lines = 0.0, [], []
    for it in items:
        p = products.get(it.get("id"))
        if not p:
            continue
        w = _weight(p) * max(1, int(it.get("qty") or 1))
        if p.kind in FREE_KINDS:
            free.append(f"{p.name}: {FREE_KINDS[p.kind]}")
            continue
        paid_w += w
        lines.append({"name": p.name, "weight_kg": round(w)})
    if paid_w == 0:
        cost = 0
    elif km <= 100:
        cost = LOCAL_COST + LOCAL_PER_KG * paid_w
    else:
        cost = max(MIN_COST, PICKUP + RATE * paid_w * km)
    cost = int(math.ceil(cost / 100) * 100)
    days = 1 if km <= 100 else math.ceil(km / 600) + 1
    return {
        "ok": True, "city": city or "", "km": round(km), "weight_kg": round(paid_w), "cost": cost,
        "days": f"{days}–{days + 2} дн." if km > 100 else "1–2 дн.",
        "lines": lines, "free": free,
        "formula": ("машина по Москве и области: 3 000 ₽ + 5 ₽/кг" if km <= 100 else
                    f"сборный груз: {PICKUP} ₽ забор + {RATE} ₽ × {round(paid_w)} кг × {round(km)} км, минимум {MIN_COST} ₽"),
        "assumption": "Условный расчёт: тариф и веса — допущения, в бою — калькулятор ТК и данные PIM.",
    }
